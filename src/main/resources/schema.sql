-- ギフト診断履歴
CREATE TABLE gift_diagnosis_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    result TEXT NOT NULL,
    diagnosis_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_gift_diagnosis_logs_user
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE CASCADE
);
 
-- ギフトタグ紐づけ
CREATE TABLE product_gift_tags (
    product_id INTEGER NOT NULL,
    tag_id INTEGER NOT NULL,
    PRIMARY KEY (product_id, tag_id),
    CONSTRAINT fk_product_gift_tags_product
        FOREIGN KEY (product_id) REFERENCES products(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_product_gift_tags_tag
        FOREIGN KEY (tag_id) REFERENCES gift_tags(id)
        ON DELETE CASCADE
);
 
-- おすすめ表示履歴
CREATE TABLE recommendation_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recommendation_reason VARCHAR(255),
    CONSTRAINT fk_recommendation_logs_user
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_recommendation_logs_product
        FOREIGN KEY (product_id) REFERENCES products(id)
        ON DELETE CASCADE
);
 
-- 関連商品
CREATE TABLE product_relations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL,
    related_product_id INTEGER NOT NULL,
    CONSTRAINT fk_product_relations_product
        FOREIGN KEY (product_id) REFERENCES products(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_product_relations_related_product
        FOREIGN KEY (related_product_id) REFERENCES products(id)
        ON DELETE CASCADE,
    CHECK (product_id <> related_product_id)
);
